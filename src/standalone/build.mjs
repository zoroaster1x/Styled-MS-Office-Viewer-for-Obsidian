/*
 * Builds the standalone spreadsheet renderer as one ES module.
 *
 *   bun src/standalone/build.mjs
 *
 * The output is what a non-Obsidian host imports. It contains the xlsx parser,
 * the grid renderer and fflate, and nothing from the Obsidian view layer.
 */

import esbuild from "esbuild";

const banner = `/*
 * Styled MS Office Viewer, standalone spreadsheet renderer.
 * Copyright (C) 2026 Zoroaster1x
 *
 * This program is free software: you can redistribute it and/or modify it under
 * the terms of the GNU General Public License as published by the Free Software
 * Foundation, either version 3 of the License, or (at your option) any later
 * version.
 *
 * Generated by src/standalone/build.mjs. The source is the spreadsheet and
 * shared folders of this repository. Do not edit this file by hand.
 */`;

await esbuild.build({
	entryPoints: ["src/standalone/xlsx-viewer.js"],
	bundle: true,
	format: "esm",
	target: "es2020",
	minify: true,
	legalComments: "inline",
	banner: { js: banner },
	outfile: "dist/xlsx-viewer.mjs",
	logLevel: "info",
});
